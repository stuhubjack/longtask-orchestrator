    c.rect(cx - r, cy - r, cx + r, cy + r, ACCENT)
    for i in range(20):
        c.rect(cx - 7 + i, cy - i // 2 - 1, cx - 6 + i, cy + i // 2 + 2, BG_BOTTOM)

    c.text("DEMO VIDEO - CLICK TO WATCH", 100, 640, 2, MUTED)

    c.save(out)
    print("✅ 封面已生成: %s (%dx%d)" % (os.path.abspath(out), W, H))


