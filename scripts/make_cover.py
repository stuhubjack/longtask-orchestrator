    c = Canvas(W, H)

    # 背景渐变
    for y in range(H):
        c.rect(0, y, W, y + 1, blend(BG_TOP, BG_BOTTOM, y / H))

    # 顶部装饰线
    c.rect(0, 0, W, 3, ACCENT)

    # 模拟终端窗口
